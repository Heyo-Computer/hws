//! Operator-directed cold recovery through the authenticated app-lb proxy.
use crate::api::{Client, seg};
use crate::error::{Error, Result};
use crate::transport::{Method, Request};
use serde::{Deserialize, Serialize};
use serde_json::Value;

/// Cloud checkpoint metadata. Timestamps retain Cloud's wire representation.
#[derive(Debug, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct RecoveryCheckpoint {
    pub checkpoint_id: String,
    pub committed_at: Value,
    pub created_at: Value,
    pub state: String,
    pub backend_id: Option<String>,
    pub runtime_id: Option<String>,
    #[serde(flatten)]
    pub extra: crate::types::Extra,
}

#[derive(Debug, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct RecoveryDestination {
    pub id: String,
    pub region: Option<String>,
    pub eligible: bool,
    pub reason: Option<String>,
    #[serde(flatten)]
    pub extra: crate::types::Extra,
}

#[derive(Debug, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct RecoveryDestinations {
    pub sandbox_id: String,
    pub source_backend_id: String,
    pub destinations: Vec<RecoveryDestination>,
    #[serde(flatten)]
    pub extra: crate::types::Extra,
}

/// Durable operation metadata; no restored environment is part of this API.
#[derive(Debug, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct RecoveryOperation {
    pub operation_id: String,
    pub sandbox_id: String,
    pub source_backend_id: String,
    pub destination_backend_id: String,
    pub recovery_checkpoint_id: String,
    pub phase: String,
    pub error: Option<String>,
    pub fencing_evidence: String,
    pub source_fenced: bool,
    pub created_at: Value,
    pub updated_at: Value,
    #[serde(flatten)]
    pub extra: crate::types::Extra,
}

/// Explicit, replayable recovery intent. No ID is generated by the client.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RecoveryRequest {
    pub operation_id: String,
    pub checkpoint_id: String,
    pub destination_backend_id: String,
    pub source_fenced: bool,
    pub fencing_evidence: String,
}

/// Validate the canonical hyphenated UUID spelling without changing caller intent.
pub fn validate_uuid(s: &str) -> std::result::Result<String, String> {
    if s.len() == 36
        && s.bytes().enumerate().all(|(i, b)| {
            if [8, 13, 18, 23].contains(&i) {
                b == b'-'
            } else {
                b.is_ascii_hexdigit()
            }
        })
    {
        Ok(s.into())
    } else {
        Err("expected a hyphenated UUID".into())
    }
}

impl RecoveryRequest {
    pub fn validate(&self) -> Result<()> {
        validate_uuid(&self.operation_id).map_err(Error::Invalid)?;
        validate_uuid(&self.checkpoint_id).map_err(Error::Invalid)?;
        if !self.source_fenced || self.fencing_evidence.trim().is_empty() {
            return Err(Error::Invalid("recovery requires source_fenced=true and nonempty fencing evidence; fence the source externally first".into()));
        }
        if self.destination_backend_id.trim().is_empty() {
            return Err(Error::Invalid(
                "choose an eligible destination backend".into(),
            ));
        }
        Ok(())
    }
}

impl Client {
    pub async fn recovery_checkpoints(&self, id: &str) -> Result<Vec<RecoveryCheckpoint>> {
        self.read(
            Request::new(
                Method::Get,
                format!("/api/vm-recovery/{}/checkpoints", seg(id)),
            ),
            "VM recovery",
            id,
        )
        .await
    }
    pub async fn recovery_destinations(&self, id: &str) -> Result<RecoveryDestinations> {
        self.read(
            Request::new(
                Method::Get,
                format!("/api/vm-recovery/{}/destinations", seg(id)),
            ),
            "VM recovery",
            id,
        )
        .await
    }
    pub async fn recoveries(&self, id: &str) -> Result<Vec<RecoveryOperation>> {
        self.read(
            Request::new(
                Method::Get,
                format!("/api/vm-recovery/{}/recoveries", seg(id)),
            ),
            "VM recovery",
            id,
        )
        .await
    }
    pub async fn recovery_status(&self, id: &str, operation_id: &str) -> Result<RecoveryOperation> {
        self.read(
            Request::new(
                Method::Get,
                format!(
                    "/api/vm-recovery/{}/recoveries/{}",
                    seg(id),
                    seg(operation_id)
                ),
            ),
            "recovery operation",
            operation_id,
        )
        .await
    }
    /// One POST only: after an ambiguous failure, inspect this operation ID.
    pub async fn start_recovery(
        &self,
        id: &str,
        request: &RecoveryRequest,
    ) -> Result<RecoveryOperation> {
        request.validate()?;
        self.read(
            Request::new(
                Method::Post,
                format!("/api/vm-recovery/{}/recoveries", seg(id)),
            )
            .json(serde_json::to_value(request).expect("serializable request")),
            "VM recovery",
            id,
        )
        .await
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::transport::stub::Stub;
    use serde_json::json;
    use std::sync::Arc;

    #[tokio::test]
    async fn request_contract_and_explicit_replay() {
        let stub = Arc::new(
            Stub::new()
                .json(200, json!([]))
                .json(200, json!({"destinations":[]}))
                .json(200, json!([]))
                .json(200, json!({}))
                .json(200, json!({}))
                .json(200, json!({})),
        );
        let c = Client::with_transport(stub.clone());
        c.recovery_checkpoints("vm/a?b").await.unwrap();
        c.recovery_destinations("vm/a?b").await.unwrap();
        c.recoveries("vm/a?b").await.unwrap();
        c.recovery_status("vm/a?b", "op/a?b").await.unwrap();
        let mut r = RecoveryRequest {
            operation_id: "12345678-1234-1234-1234-123456789abc".into(),
            checkpoint_id: "abcdefab-1234-1234-1234-123456789abc".into(),
            destination_backend_id: "eu1".into(),
            source_fenced: false,
            fencing_evidence: "power disabled".into(),
        };
        assert!(c.start_recovery("vm", &r).await.is_err());
        r.source_fenced = true;
        r.fencing_evidence = "  ".into();
        assert!(c.start_recovery("vm", &r).await.is_err());
        assert_eq!(stub.calls().len(), 4);
        r.fencing_evidence = "power disabled".into();
        c.start_recovery("vm/a?b", &r).await.unwrap();
        c.start_recovery("vm/a?b", &r).await.unwrap();
        let calls = stub.calls();
        for (i, suffix) in [
            "checkpoints",
            "destinations",
            "recoveries",
            "recoveries/op%2Fa%3Fb",
            "recoveries",
            "recoveries",
        ]
        .iter()
        .enumerate()
        {
            assert_eq!(
                calls[i].path,
                format!("/api/vm-recovery/vm%2Fa%3Fb/{suffix}")
            );
            assert_eq!(
                calls[i].method,
                if i < 4 { Method::Get } else { Method::Post }
            );
        }
        assert_eq!(calls[4].body, calls[5].body);
        assert_eq!(
            calls[4].body,
            Some(
                json!({"operation_id":r.operation_id,"checkpoint_id":r.checkpoint_id,"destination_backend_id":"eu1","source_fenced":true,"fencing_evidence":"power disabled"})
            )
        );
    }
}
